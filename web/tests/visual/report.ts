import fs from 'node:fs';
import path from 'node:path';
import { PAGES, PASS_MAX_DIFF_RATIO, PIXELMATCH_THRESHOLD } from './contract';
import type { Capture, PageResult } from './harness';
import { reportsDir, resultsDir } from './paths';

function readResult(name: string): PageResult | null {
  try {
    return JSON.parse(fs.readFileSync(path.join(resultsDir, `${name}.json`), 'utf8')) as PageResult;
  } catch {
    return null;
  }
}

const shift = (c: Capture | null) => (c ? String(Number(c.layoutShift.toFixed(4))) : '–');
const stable = (c: Capture | null) => (c ? (c.stable ? 'yes' : 'no') : '–');

export function renderReport(): string {
  const lines = [
    '# Visual report',
    '',
    `Regenerated by \`npm run visual\` on every run. Contract (\`tests/visual/contract.ts\`): pixelmatch threshold ${PIXELMATCH_THRESHOLD}, pass at ≤ ${(PASS_MAX_DIFF_RATIO * 100).toFixed(1)}% differing pixels of the viewport, built-page layout shift 0 (reference shift reported only), screenshots 500 ms apart identical.`,
    '',
    '| page | viewport | diff % | pass/fail | layout shift (ref / built) | stable (ref / built) |',
    '|---|---|---|---|---|---|',
  ];
  const notes: string[] = [];
  for (const p of PAGES) {
    const r = readResult(p.name);
    const vp = `${p.viewport.width}x${p.viewport.height}`;
    if (!r) {
      lines.push(`| ${p.name} | ${vp} | – | not run | – | – |`);
      continue;
    }
    const pct = r.diffRatio === null ? '–' : (r.diffRatio * 100).toFixed(2);
    const verdict = r.error ? 'error' : r.pass ? 'pass' : 'fail';
    lines.push(`| ${p.name} | ${vp} | ${pct} | ${verdict} | ${shift(r.reference)} / ${shift(r.built)} | ${stable(r.reference)} / ${stable(r.built)} |`);
    const detail = [`${r.diffPixels ?? '–'} of ${r.totalPixels} px differ`];
    if (r.reference) detail.push(`Figtree faces loaded: ref ${r.reference.figtreeLoaded}, built ${r.built?.figtreeLoaded ?? '–'}`);
    const blocked = [...(r.reference?.blocked ?? []), ...(r.built?.blocked ?? [])];
    if (blocked.length) detail.push(`blocked requests: ${blocked.join(', ')}`);
    if (r.error) detail.push(`error: ${r.error.split('\n')[0]}`);
    notes.push(`- **${p.name}**: ${detail.join('; ')}. Images: \`${p.name}-reference.png\`, \`${p.name}-built.png\`, \`${p.name}-diff.png\`.`);
  }
  return [...lines, '', ...notes, ''].join('\n');
}

export function writeReport(): void {
  fs.mkdirSync(reportsDir, { recursive: true });
  fs.writeFileSync(path.join(reportsDir, 'visual-report.md'), renderReport());
}
