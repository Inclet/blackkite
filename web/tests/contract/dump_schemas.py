"""Dump the member API's response JSON schemas for the web contract test.

Run from the api/ directory (it imports the API's own Pydantic models):

    cd api && uv run python ../web/tests/contract/dump_schemas.py

It rewrites web/tests/contract/api-schemas.json. Validation-mode schemas with
camelCase aliases: a field with a default is optional (the API leaves it out
when empty); a field without one is always sent.
"""

from __future__ import annotations

import json
from pathlib import Path

from pydantic import BaseModel
from pydantic.alias_generators import to_camel

from blackkite.member import profiles as P
from blackkite.member import schemas as S
from blackkite.routes.digest_settings import DigestSettingsIn, DigestSettingsOut
from blackkite.routes.schemas import UserOut

MODELS = {
    # Responses.
    "FeedContent": S.FeedContent,
    "FeedItem": S.FeedItem,
    "OpportunityOut": S.OpportunityOut,
    "ProfileOut": P.ProfileOut,
    "DigestSettingsOut": DigestSettingsOut,
    "UserOut": UserOut,
    # ProfileOut.data is a dict; these are its shapes per type.
    "BusinessData": P.BusinessData,
    "PersonalData": P.PersonalData,
    # Request bodies the web app sends.
    "ProfileIn": P.ProfileIn,
    "DigestSettingsIn": DigestSettingsIn,
    "StateIn": S.StateIn,
}



def omitted_when_empty(model: type[BaseModel], seen: dict[str, list[str]]) -> None:
    """Fields the API drops from the JSON when None (CamelModel.omit_if_none),
    by model title, for this model and every model it nests."""
    if model.__name__ in seen:
        return
    names = getattr(model, "omit_if_none", frozenset())
    seen[model.__name__] = sorted(to_camel(n) for n in names)
    for field in model.model_fields.values():
        stack = [field.annotation]
        while stack:
            t = stack.pop()
            if isinstance(t, type) and issubclass(t, BaseModel):
                omitted_when_empty(t, seen)
            stack.extend(getattr(t, "__args__", ()))


omit: dict[str, list[str]] = {}
for m in MODELS.values():
    omitted_when_empty(m, omit)

out = {
    "$comment": "Generated by web/tests/contract/dump_schemas.py from the API's Pydantic models. Do not edit by hand.",
    "schemas": {
        name: model.model_json_schema(by_alias=True, mode="validation")
        for name, model in MODELS.items()
    },
    # By model title: keys the API leaves out of the JSON rather than send null.
    "omitIfNone": {k: v for k, v in sorted(omit.items()) if v},
}
path = Path(__file__).with_name("api-schemas.json")
path.write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
print(f"wrote {path}")
